import os
import fnmatch
import json
from pathlib import Path

def find_files(root: Path, pattern: str):
    """Recursively find files matching the given glob pattern under root."""
    return [str(p.relative_to(root)) for p in root.rglob(pattern) if p.is_file()]

def generate_audit_report() -> str:
    repo_root = Path(__file__).resolve().parents[1]
    report_lines = []
    report_lines.append("# Quality Evaluation Feature Audit Report\n")
    report_lines.append("## Discovered Files\n")

    # Core module files
    core_files = find_files(repo_root, "quality_evaluation/**/*.py")
    if core_files:
        report_lines.append("### quality_evaluation package\n")
        for f in sorted(core_files):
            report_lines.append(f"- `{f}`")
    else:
        report_lines.append("*No files found in `quality_evaluation/` package.*")

    # Test suites
    test_files = find_files(repo_root, "tests/quality_evaluation/**/*.py")
    if test_files:
        report_lines.append("\n### Test suites under `tests/quality_evaluation/`\n")
        for f in sorted(test_files):
            report_lines.append(f"- `{f}`")
    else:
        report_lines.append("\n*No test files found for quality evaluation.*")

    # CI configuration snippets
    ci_files = []
    for ci_path in [".github/workflows/*.yml", ".github/workflows/*.yaml", "ci/*.yml", "ci/*.yaml"]:
        ci_files.extend(find_files(repo_root, ci_path))
    if ci_files:
        report_lines.append("\n### CI configuration snippets\n")
        for f in sorted(ci_files):
            report_lines.append(f"- `{f}`")
    else:
        report_lines.append("\n*No CI configuration files detected.*")

    # Identify gaps
    report_lines.append("\n## Identified Gaps\n")
    if not core_files:
        report_lines.append("- Missing core implementation module `quality_evaluation/__init__.py` and related code.")
    if not test_files:
        report_lines.append("- No unit or integration tests for the quality evaluation feature.")
    if not any("quality_evaluation" in f for f in ci_files):
        report_lines.append("- CI does not currently invoke any quality‑evaluation tests or linting steps.")
    if core_files and test_files:
        report_lines.append("- Implementation placeholders exist but tests are likely failing or incomplete; further steps should add schema, engine, and API.")

    report_lines.append("\n*Generated by `tools/quality_evaluation_audit.py`.*")
    return "\n".join(report_lines)

if __name__ == "__main__":
    print(generate_audit_report())
